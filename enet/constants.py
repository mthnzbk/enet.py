# ==============================================================================
# Packet Flags
# ==============================================================================
PACKET_FLAG_RELIABLE = 1 << 0
"""Packet must be received by target peer; resend attempts made until delivered."""

PACKET_FLAG_UNSEQUENCED = 1 << 1
"""Packet will not be sequenced with other packets (not supported for reliable)."""

PACKET_FLAG_NO_ALLOCATE = 1 << 2
"""Packet will not allocate data, user supplies it."""

PACKET_FLAG_UNRELIABLE_FRAGMENT = 1 << 3
"""Packet fragmented using unreliable sends if it exceeds MTU."""

PACKET_FLAG_UNTHROTTLED = 1 << 4
"""Unreliable packet should not be dropped due to throttling."""

PACKET_FLAG_SENT = 1 << 8
"""Whether the packet has been sent from all queues it has been entered into."""

# pyenet aliases
ENET_PACKET_FLAG_RELIABLE = PACKET_FLAG_RELIABLE
